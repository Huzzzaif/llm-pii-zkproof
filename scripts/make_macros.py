"""Turn eval/results/*.json into LaTeX macros (paper/numbers.tex).
The paper uses only these macros for measured values, so every number is traceable.

    python3 scripts/make_macros.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
R = ROOT / "eval" / "results"
out = ["% GENERATED by scripts/make_macros.py from eval/results/*.json -- do not edit"]
WORDS = {64: "SixtyFour", 128: "OneTwentyEight", 256: "TwoFiftySix", 512: "FiveTwelve", 1024: "TenTwentyFour"}


def mac(name, val):
    out.append(f"\\newcommand{{\\{name}}}{{{val}}}")


def key(k):
    return k.replace("_", "").replace("4", "four").capitalize()


def pct(x):
    return f"{100 * x:.1f}\\%"


def comma(n):
    return f"{n:,}"


bench = json.loads((R / "bench.json").read_text()) if (R / "bench.json").exists() else None
if bench:
    mac("hwName", bench["hardware"].replace("Apple ", ""))
    mac("nargoVer", bench["nargo"].split("=")[-1].strip())
    mac("bbVer", bench["bb"])
    mac("benchRuns", bench["runs"])
    for row in bench["scaling"]:
        w = WORDS[row["N"]]
        mac(f"gates{w}", comma(row["gates"]))
        mac(f"prove{w}", f"{row['prove_s']['median']:.2f}")
        mac(f"verify{w}", f"{1000 * row['verify_s']['median']:.0f}")
        mac(f"witness{w}", f"{row['witness_s']['median']:.2f}")
        mac(f"mem{w}", f"{row['prove_peak_mib']:.0f}")
        mac(f"proofKB{w}", f"{row['proof_bytes'] / 1024:.1f}")
    b = bench["breakdown_n256"]
    for k, v in b.items():
        mac("gatesBd" + key(k), comma(v))
    for k in ["ssn", "email", "phone_us", "ipv4", "date", "card"]:
        mac("gatesInc" + key(k), comma(b[k] - b["none"]))

det = json.loads((R / "detector_eval.json").read_text())
for ds, tag in [("ai4privacy_500", "Ai"), ("synth_500", "Syn")]:
    d = det[ds]
    mac(f"refusal{tag}", pct(d["refusal_rate_in_scope"]))
    mac(f"falseRefusal{tag}", pct(d["false_refusal_rate_scrubbed"]))
    mac(f"inScope{tag}", d["records_with_in_scope_pii"])
    for k, t in d["per_type"].items():
        kk = key(k)
        mac(f"rec{tag}{kk}", f"{t['recall']:.3f}")
        mac(f"recN{tag}{kk}", f"{t['hits']}/{t['n']}")

agr = R / "circuit_agreement.json"
if agr.exists():
    a = json.loads(agr.read_text())
    mac("agreeCases", a["cases"])
    mac("agreeOk", a["agree"])

llm = R / "llm_outputs.json"
if llm.exists():
    s = json.loads(llm.read_text())["summary"]
    mac("llmModel", s["model"])
    mac("llmResponses", s["responses"])
    mac("llmWithPii", s["responses_with_pii"])
    mac("llmRefused", s["refused_of_pii_responses"])
    mac("llmBenign", s["benign_responses"])
    mac("llmBenignRefused", s["benign_refused"])
    mac("llmMedianBytes", s["median_bytes"])
    mac("llmMaxBytes", s["max_bytes"])
    for k, v in s["per_type_value_caught"].items():
        mac("llmCaught" + key(k), f"{v['caught']}/{v['n']}")

pres = R / "presidio_eval.json"
if pres.exists():
    pr = json.loads(pres.read_text())
    for ds, tag in [("ai4privacy_500", "Ai"), ("synth_500", "Syn")]:
        d = pr[ds]
        mac(f"presRefusal{tag}", pct(d["refusal_rate_in_scope"]))
        mac(f"presFalseRefusal{tag}", pct(d["false_refusal_rate_scrubbed"]))
        for k, t in d["per_type"].items():
            kk = key(k.lower())
            mac(f"pres{tag}{kk}", f"{t['recall']:.3f}")
            mac(f"presN{tag}{kk}", f"{t['hits']}/{t['n']}")

bt = R / "bench_tee.json"
if bt.exists():
    b = json.loads(bt.read_text())
    mac("teeGates", comma(b["gates"]))
    mac("teeProve", f"{b['prove_s']:.2f}")
    mac("teeVerify", f"{1000 * b['verify_s']:.0f}")
    mac("teeMem", f"{b['prove_peak_mib']:.0f}")
    mac("teeNerMs", f"{1000 * b['ner_s']:.0f}")
    mac("teeSignMs", f"{1000 * b['sign_s']:.1f}")
    if bench:
        mac("teeExtraGates", comma(b["gates"] - [r for r in bench["scaling"] if r["N"] == 256][0]["gates"]))

ts = R / "tee_soundness.json"
if ts.exists():
    t = json.loads(ts.read_text())
    mac("teeAttacks", sum(1 for c in t["cases"] if c["case"] != "honest labels, names forbidden"))
    mac("teeAttacksRefused", sum(1 for c in t["cases"] if c["case"] != "honest labels, names forbidden" and c["outcome"] == "refused"))

(ROOT / "paper" / "numbers.tex").write_text("\n".join(out) + "\n")
print(f"wrote paper/numbers.tex ({len(out) - 1} macros)")

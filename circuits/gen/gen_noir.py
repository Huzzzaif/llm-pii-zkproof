"""Emit the ZKPriv Noir circuit from the detector DFAs.

Output: circuits/zkpriv/{Nargo.toml, src/main.nr, src/tables.nr}
Each detector becomes a byte-class map (256 entries) plus a transition table
(states x classes). Accepting states are absorbing and minimization merges
them, so each detector has exactly one accepting state and the circuit only
checks the state after the final boundary byte.
"""
import sys
from pathlib import Path

from card_dfa import build_card_dfa
from detectors import build_all
from regex_dfa import BOUNDARY

N_DEFAULT = 256
CHUNK = 31  # bytes per field element (fits below the BN254 modulus)
ORDER = ["ssn", "email", "phone_us", "ipv4", "date", "card", "date_text", "phone_intl",
         "dob", "longnum", "id_prefixed", "iban", "email_obf"]  # policy mask bit = index
ASCII_BIT = len(ORDER)  # 13
SEM_SHIFT = ASCII_BIT + 1  # tier-2 semantic categories use policy bits 14..17


def compress(d):
    cols: dict = {}
    cls = [cols.setdefault(tuple(d.table[s][b] for s in range(d.n_states)), len(cols)) for b in range(256)]
    nc = len(cols)
    rep = {c: b for b, c in reversed(list(enumerate(cls)))}  # one byte per class
    trans = [d.table[s][rep[c]] for s in range(d.n_states) for c in range(nc)]
    (acc,) = d.accept
    return cls, trans, nc, acc


def arr(xs):
    return "[" + ", ".join(map(str, xs)) + "]"


def emit(out_dir: Path, n: int, detectors=None, pkg: str = None, tee: bool = False, helper: bool = False):
    detectors = detectors if detectors is not None else ORDER
    dfas = build_all()
    dfas["card"] = build_card_dfa()
    tables, fns = [], []
    for name in detectors:
        d = dfas[name]
        cls, trans, nc, acc = compress(d)
        U = name.upper()
        start_after_boundary = d.table[d.start][BOUNDARY]
        tables.append(
            f"pub global {U}_CLS: [u32; 256] = {arr(cls)};\n"
            f"pub global {U}_T: [u32; {len(trans)}] = {arr(trans)};\n"
            f"pub global {U}_NC: u32 = {nc};\n"
            f"pub global {U}_ACC: u32 = {acc};\n"
            f"pub global {U}_S0: u32 = {start_after_boundary};\n"
            f"pub global {U}_BOUNDARY_CLS: u32 = {cls[BOUNDARY]};\n"
        )
        fns.append(f"""
// {name}: {d.n_states} states, {nc} byte classes
fn detect_{name}(y: [u8; N], len: u32) -> bool {{
    let mut s: u32 = tables::{U}_S0;
    for i in 0..N {{
        if i < len {{
            let c = tables::{U}_CLS[y[i] as u32];
            s = tables::{U}_T[s * tables::{U}_NC + c];
        }}
    }}
    s = tables::{U}_T[s * tables::{U}_NC + tables::{U}_BOUNDARY_CLS];
    s == tables::{U}_ACC
}}""")

    n_chunks = -(-n // CHUNK)
    checks = "\n".join(
        f"    assert(!(bit(policy_mask, {i}) & detect_{name}(y, len)), \"policy violation: {name}\");"
        for i, name in enumerate(ORDER) if name in detectors
    )
    tee_params = ("    sem: u32,\n    sig: [u8; 64],\n    pk_x: pub [u8; 32],\n    pk_y: pub [u8; 32],\n") if tee else ""
    tee_body = (f"""    // Tier 2: semantic labels computed and signed by an attested enclave over com.
    let digest: [u8; 32] = p2_hash([com, sem as Field]).to_be_bytes();
    assert(std::ecdsa_secp256k1::verify_signature(pk_x, pk_y, sig, digest), "bad enclave signature");
    assert((sem & (policy_mask >> {SEM_SHIFT})) == 0, "policy violation: semantic");
""") if tee else ""
    main = f"""// GENERATED by circuits/gen/gen_noir.py — do not edit by hand.
// ZKPriv: prove a committed response contains no structured PII forbidden by the policy.
mod tables;


global N: u32 = {n};
global CHUNK: u32 = {CHUNK};
global N_CHUNKS: u32 = {n_chunks};

/// Poseidon2 sponge over BN254: width 4, rate 3, capacity 1; the input
/// length is domain-separated into the capacity element.
fn p2_hash<let L: u32>(input: [Field; L]) -> Field {{
    let mut state: [Field; 4] = [0, 0, 0, (L as Field) * 18446744073709551616];
    for c in 0..(L + 2) / 3 {{
        for j in 0..3 {{
            let k = c * 3 + j;
            if k < L {{
                state[j] += input[k];
            }}
        }}
        state = std::hash::poseidon2_permutation(state);
    }}
    state[0]
}}

fn bit(mask: u32, k: u32) -> bool {{
    ((mask >> k) & 1) == 1
}}

/// Commitment over packed bytes (31 per field element), length, blinding and request id.
fn commit_y(y: [u8; N], len: u32, rho: Field, pid: Field) -> Field {{
    let mut inp: [Field; N_CHUNKS + 3] = [0; N_CHUNKS + 3];
    for c in 0..N_CHUNKS {{
        let mut acc: Field = 0;
        for j in 0..CHUNK {{
            let idx = c * CHUNK + j;
            if idx < N {{
                acc = acc * 256 + y[idx] as Field;
            }}
        }}
        inp[c] = acc;
    }}
    inp[N_CHUNKS] = len as Field;
    inp[N_CHUNKS + 1] = rho;
    inp[N_CHUNKS + 2] = pid;
    p2_hash(inp)
}}
{''.join(fns)}

/// Public: request id `pid`. Public outputs: response commitment and policy hash.
/// Private: response bytes (zero-padded to N), length, blinding factor, policy.
fn main(
    y: [u8; N],
    len: u32,
    rho: Field,
    policy_mask: u32,
    policy_version: Field,
    pid: pub Field,
{tee_params}) -> pub [Field; 2] {{
    // Length and padding binding: real bytes are non-zero, padding is zero.
    assert(len <= N);
    for i in 0..N {{
        if i < len {{
            assert(y[i] != 0, "NUL byte inside response");
        }} else {{
            assert(y[i] == 0, "non-zero padding");
        }}
    }}
    // Optional canonicalization guard: ASCII-only responses (blocks Unicode look-alike digits).
    if bit(policy_mask, {ASCII_BIT}) {{
        for i in 0..N {{
            assert(y[i] < 128, "non-ASCII byte under ascii_only policy");
        }}
    }}
{checks}

    let com = commit_y(y, len, rho, pid);
    let h_pol = p2_hash([policy_mask as Field, policy_version]);
{tee_body}    [com, h_pol]
}}
"""
    if helper:
        main = main[: main.index("/// Public: request id")] + """/// Helper for the enclave: returns (com, digest) exactly as the main circuit computes them.
fn main(y: [u8; N], len: u32, rho: Field, pid: Field, sem: u32) -> pub [Field; 2] {
    let com = commit_y(y, len, rho, pid);
    [com, p2_hash([com, sem as Field])]
}
"""
    src = out_dir / "src"
    src.mkdir(parents=True, exist_ok=True)
    (out_dir / "Nargo.toml").write_text(
        f'[package]\nname = "{pkg or f"zkpriv_n{n}"}"\ntype = "bin"\nauthors = ["Huzaif Khan"]\n\n[dependencies]\n'
    )
    (src / "main.nr").write_text(main)
    (src / "tables.nr").write_text("// GENERATED by circuits/gen/gen_noir.py\n" + "\n".join(tables))
    print(f"wrote {out_dir} (N={n}, {n_chunks} chunks)")


if __name__ == "__main__":
    flags = {a for a in sys.argv[1:] if a.startswith("--")}
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    n = int(args[0]) if args else N_DEFAULT
    root = Path(__file__).resolve().parents[1]
    if "--tee" in flags:
        emit(root / f"zkpriv_tee_n{n}", n, pkg=f"zkpriv_tee_n{n}", tee=True)
        sys.exit(0)
    if "--helper" in flags:
        emit(root / f"digest_n{n}", n, detectors=[], pkg=f"digest_n{n}", helper=True)
        sys.exit(0)
    dets = args[1].split(",") if len(args) > 1 else None
    if dets is None:
        emit(root / (f"zkpriv_n{n}" if n != N_DEFAULT else "zkpriv"), n)
    else:
        tag = "none" if dets == [""] else "_".join(dets)
        dets = [] if dets == [""] else dets
        emit(root / "variants" / f"n{n}_{tag}", n, dets, pkg=f"zkpriv_n{n}_{tag}")
